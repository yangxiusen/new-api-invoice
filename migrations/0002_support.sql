CREATE TABLE invoice_user_permissions (
 user_id bigint PRIMARY KEY, enabled boolean NOT NULL DEFAULT false,
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0), source varchar(32) NOT NULL,
 initialization_batch uuid, updated_by bigint, remark varchar(512) NOT NULL DEFAULT '',
 created_at bigint NOT NULL, updated_at bigint NOT NULL
);
CREATE INDEX ON invoice_user_permissions(enabled,user_id);
CREATE TABLE invoice_operation_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, occurred_at bigint NOT NULL,
 actor_type varchar(16) NOT NULL, actor_user_id bigint, actor_name varchar(255) NOT NULL,
 target_user_id bigint NOT NULL, operation_type varchar(32) NOT NULL, application_id bigint,
 request_no varchar(64), before_state varchar(64) NOT NULL DEFAULT '', after_state varchar(64) NOT NULL DEFAULT '',
 remark varchar(512) NOT NULL DEFAULT '', request_id uuid NOT NULL,
 write_request_id uuid UNIQUE, initialization_batch uuid
);
CREATE INDEX ON invoice_operation_logs(target_user_id,occurred_at DESC,id DESC);
CREATE INDEX ON invoice_operation_logs(actor_user_id,occurred_at DESC,id DESC);
CREATE INDEX ON invoice_operation_logs(operation_type,occurred_at DESC,id DESC);
CREATE INDEX ON invoice_operation_logs(application_id,id);
CREATE TABLE invoice_write_requests (
 id uuid PRIMARY KEY, actor_user_id bigint NOT NULL, idempotency_key uuid NOT NULL,
 operation varchar(128) NOT NULL, request_hash char(64) NOT NULL, response_ref jsonb NOT NULL,
 result_code varchar(64) NOT NULL, requires_admin boolean NOT NULL DEFAULT false, created_at bigint NOT NULL,
 UNIQUE(actor_user_id,idempotency_key)
);
CREATE TABLE invoice_initializations (
 name varchar(64) PRIMARY KEY, batch_id uuid NOT NULL UNIQUE, global_enabled boolean NOT NULL,
 source_kind varchar(32) NOT NULL, source_fingerprint char(64) NOT NULL,
 snapshot_max_user_id bigint NOT NULL, snapshot_user_count bigint NOT NULL,
 inserted_count bigint NOT NULL, enabled_count bigint NOT NULL, skipped_count bigint NOT NULL, completed_at bigint NOT NULL
);
